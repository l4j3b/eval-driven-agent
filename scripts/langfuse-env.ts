// Writes langfuse/.env for the self-hosted Langfuse stack, with fresh random
// secrets, and fills the Langfuse keys in .env.local if they're blank.
//
//   npm run langfuse:env
//
// Never overwrites an existing langfuse/.env: its secrets encrypt data that's
// already in the stack's volumes.
import { randomBytes, randomUUID } from "node:crypto";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";

const TARGET = "langfuse/.env";
const APP_ENV = ".env.local";

if (existsSync(TARGET)) {
	console.log(`${TARGET} already exists; leaving it alone.`);
	process.exit(0);
}

const hex = (bytes: number) => randomBytes(bytes).toString("hex");
const base64 = (bytes: number) => randomBytes(bytes).toString("base64");

const postgresPassword = hex(16);
const minioPassword = hex(16);
const publicKey = `pk-lf-${randomUUID()}`;
const secretKey = `sk-lf-${randomUUID()}`;

const values = {
	TELEMETRY_ENABLED: "false",
	NEXTAUTH_URL: "http://localhost:3000",
	NEXTAUTH_SECRET: base64(32),
	SALT: base64(32),
	ENCRYPTION_KEY: hex(32),
	POSTGRES_PASSWORD: postgresPassword,
	DATABASE_URL: `postgresql://postgres:${postgresPassword}@postgres:5432/postgres`,
	CLICKHOUSE_PASSWORD: hex(16),
	REDIS_AUTH: hex(16),
	// The org, project and API keys Langfuse creates on its first start.
	LANGFUSE_INIT_ORG_ID: "agent-lab",
	LANGFUSE_INIT_ORG_NAME: '"Agent Lab"',
	LANGFUSE_INIT_PROJECT_ID: "agent-lab",
	LANGFUSE_INIT_PROJECT_NAME: "agent-lab",
	LANGFUSE_INIT_PROJECT_PUBLIC_KEY: publicKey,
	LANGFUSE_INIT_PROJECT_SECRET_KEY: secretKey,
	// Anyone who signs up in this local instance joins that project as owner.
	LANGFUSE_DEFAULT_ORG_ID: "agent-lab",
	LANGFUSE_DEFAULT_ORG_ROLE: "OWNER",
	LANGFUSE_DEFAULT_PROJECT_ID: "agent-lab",
	LANGFUSE_DEFAULT_PROJECT_ROLE: "OWNER",
	// MinIO stands in for S3; Langfuse logs in to it with the root password.
	MINIO_ROOT_PASSWORD: minioPassword,
	LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY: minioPassword,
	LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY: minioPassword,
	LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY: minioPassword,
};

await writeFile(
	TARGET,
	[
		"# Local-only secrets for the self-hosted Langfuse stack. Generated by npm run langfuse:env; gitignored.",
		...Object.entries(values).map(([key, value]) => `${key}=${value}`),
		"",
	].join("\n"),
	{ mode: 0o600 },
);
console.log(`Wrote ${TARGET}.`);

// Point the app at the project's keys, unless .env.local already has some.
if (!existsSync(APP_ENV)) {
	console.log(
		`No ${APP_ENV} yet: copy .env.example to ${APP_ENV} and run this again after deleting ${TARGET}, or copy LANGFUSE_INIT_PROJECT_PUBLIC_KEY and _SECRET_KEY from ${TARGET} yourself.`,
	);
	process.exit(0);
}
let appEnv = await readFile(APP_ENV, "utf8");
let filled = 0;
for (const [key, value] of [
	["LANGFUSE_PUBLIC_KEY", publicKey],
	["LANGFUSE_SECRET_KEY", secretKey],
]) {
	const blank = new RegExp(`^${key}=\\s*$`, "m");
	if (blank.test(appEnv)) {
		appEnv = appEnv.replace(blank, `${key}=${value}`);
		filled++;
	}
}
await writeFile(APP_ENV, appEnv);
console.log(
	filled
		? `Filled the Langfuse keys in ${APP_ENV}.`
		: `${APP_ENV} already has Langfuse keys; make sure they match ${TARGET}.`,
);
